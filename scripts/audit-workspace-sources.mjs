import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { normalize, readBackendRoutes, walk } from './source-route-inventory.mjs';

const workspace = path.resolve('..');
const backend = path.join(workspace, 'fptu-xperience-clubhub-api');
const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: backend, encoding: 'utf8' }).trim();
const { routes, unresolvedGroups } = readBackendRoutes(backend);
const consumers = [];
for (const repo of ['fptu-xperience-clubhub-ui', 'fptu-xperience-admin-ui']) {
    const root = path.join(workspace, repo);
    for (const file of walk(path.join(root, 'src')).filter(
        (f) => /\.(jsx?|tsx?)$/.test(f) && !/\.test\./.test(f) && !/[\\/]Demo|[\\/]model\.js$|[\\/]ui\.jsx$/.test(f),
    )) {
        const source = fs.readFileSync(file, 'utf8');
        for (const match of source.matchAll(/['"`](\/api\/[^'"`\n]*)/g))
            consumers.push({
                route: normalize(match[1]),
                file: `${repo}/${path.relative(root, file).replaceAll('\\', '/')}`,
                line: source.slice(0, match.index).split('\n').length,
            });
    }
}
const gateway = JSON.parse(fs.readFileSync(path.join(backend, 'src/Gateway/ApiGateway/yarp.json'), 'utf8')).ReverseProxy
    .Routes;
const gatewayRoutes = Object.entries(gateway).map(([name, value]) => ({
    name,
    ...value,
    pattern: new RegExp(
        '^' +
            value.Match.Path.split(/(\{[^}]+\})/)
                .map((part) =>
                    part.startsWith('{')
                        ? part.includes('**')
                            ? '.*'
                            : '[^/]+'
                        : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'),
                )
                .join('') +
            '/?$',
    ),
}));
const publicRoutes = routes.filter((r) => r.route.startsWith('/api/') && !r.route.startsWith('/api/internal/'));
const inventory = publicRoutes.map((route) => ({
    ...route,
    consumers: consumers.filter((consumer) => consumer.route === route.route),
    gatewayCandidates: gatewayRoutes
        .filter((g) => g.pattern.test(route.route))
        .map((g) => `${g.name}:${g.ClusterId}:order=${g.Order ?? 0}`),
}));
const unmatched = consumers.filter((c) => !publicRoutes.some((r) => c.route === r.route));
const output = path.join(process.cwd(), 'docs/qa/workspace-source-inventory.md');
const services = [...new Set(publicRoutes.map((r) => r.file.split('/')[2]))];
fs.writeFileSync(
    output,
    `# Workspace source inventory — 2026-10-19

Backend: ${head}. Generated by \`node scripts/audit-workspace-sources.mjs\`.

${routes.length} resolved method/path declarations; ${publicRoutes.length} public API declarations after excluding internal workflow and non-API routes. ${unresolvedGroups.length} unresolved receiver declarations. Includes explicit aliases. This is a bounded source extractor, not reflection/OpenAPI, DTO compatibility, handler reachability, or E2E proof. Dynamic path composition, runtime prefixes and nonliteral calls need manual review. Consumer matching below is PATH ONLY; matching a path does not prove the HTTP method, body, authorization, or a rendered caller. Missing literal consumers are review candidates, not automatically absent business flows. Gateway candidates are possible path matches, not a computed YARP precedence/authorization verdict.

| Service | Public declarations |
| --- | --- |
${services.map((s) => `| ${s} | ${publicRoutes.filter((r) => r.file.split('/')[2] === s).length} |`).join('\n')}

## Every resolved public declaration

| HTTP | Path | Backend evidence | FE literal path references | Gateway candidates |
| --- | --- | --- | --- | --- |
${inventory.map((r) => `| ${r.method} | \`${r.route}\` | ${r.file}:${r.line} | ${r.consumers.map((c) => `${c.file}:${c.line}`).join('<br>') || 'MANUAL REVIEW: no exact literal consumer'} | ${r.gatewayCandidates.join('<br>') || 'MANUAL REVIEW: no path candidate'} |`).join('\n')}

## FE paths without an exact declaration

Dynamic suffixes, health probes and provisional contracts are included. Check the flow audit before classifying these as backend gaps.

| FE path | Evidence |
| --- | --- |
${unmatched.map((c) => `| \`${c.route}\` | ${c.file}:${c.line} |`).join('\n')}

## Extractor limits / unresolved receivers

${unresolvedGroups.join('\n') || 'No unresolved receivers in the handled declaration syntax. This does not assert that all possible C# endpoint syntax is handled.'}
`,
);
console.log(
    JSON.stringify({
        resolvedDeclarations: routes.length,
        publicDeclarations: publicRoutes.length,
        consumerLiterals: consumers.length,
        unmatchedLiterals: unmatched.length,
        unresolvedGroups,
        output,
    }),
);
